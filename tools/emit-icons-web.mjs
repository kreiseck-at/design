export const pascal = (id) => id.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");

const HAND = 'fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"';

// Web keeps the source shapes instead of flattened cubics: browsers render a
// <rect> or <circle> crisper than an approximated curve, and the file stays readable.
const withRx = (el) => (el.tag === "rect" && !("rx" in el.attrs) ? { ...el, attrs: { ...el.attrs, rx: "2.5" } } : el);
const attrString = (attrs) => Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(" ");
export const elementsSvg = (elements) => elements.map(withRx).map((e) => `<${e.tag} ${attrString(e.attrs)}/>`).join("");
const nodesTs = (elements) => elements.map(withRx).map((e) => `["${e.tag}", { ${Object.entries(e.attrs).map(([k, v]) => `${/^[a-z]+$/.test(k) ? k : `"${k}"`}: "${v}"`).join(", ")} }]`).join(",\n    ");

const component = (name, id, elements) => `// Generated by tools/build.mjs. Do not edit.
import { createIcon } from "./create-icon.js";

export const ${name} = createIcon("${id}", [
    ${nodesTs(elements)}
]);
`;

export function emitIconsWeb(model) {
  const files = [], exportsTs = [], names = [], symbols = [];
  const add = (id, elements) => {
    const name = pascal(id);
    files.push([`packages/npm/src/icons/${name}.tsx`, component(name, id, elements)]);
    files.push([`packages/npm/svg/${id}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" ${HAND}>${elementsSvg(elements)}</svg>\n`]);
    exportsTs.push(`export { ${name} } from "./${name}.js";`);
    names.push(id);
    symbols.push(`<symbol id="kd-${id}" viewBox="0 0 24 24">${elementsSvg(elements)}</symbol>`);
  };
  for (const id of model.order) {
    add(id, model.icons[id].stroke);
    if (model.icons[id].filled) add(`${id}-filled`, model.icons[id].fill);
  }
  files.push(["packages/npm/src/icons/index.ts", `// Generated by tools/build.mjs. Do not edit.\n${exportsTs.join("\n")}\nexport { createIcon } from "./create-icon.js";\nexport type { IconProps } from "./create-icon.js";\nexport const iconNames = [${names.map((n) => `"${n}"`).join(", ")}] as const;\n`]);
  files.push(["packages/npm/svg/sprite.svg", `<svg xmlns="http://www.w3.org/2000/svg" ${HAND} style="display:none">${symbols.join("")}</svg>\n`]);
  return { files };
}

// Exported under this name too: the gallery (a later addition) renders icons
// inline without pulling in the whole generator, just the element markup.
export const iconSvgInner = elementsSvg;
