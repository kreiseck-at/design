const json = (v) => JSON.stringify(v);

export function emitLogoWeb(logo, animations) {
  const glyphs = logo.glyphs.map((g) => `  { char: ${json(g.char)}, bbox: ${json(g.bbox)}, d: ${json(g.d)} }`).join(",\n");
  const cells = logo.cells.map((c) => `  { index: ${c.index}, row: ${c.row}, col: ${c.col}, part: "${c.part}" }`).join(",\n");
  const anims = animations.map((a) => `  ${json(a.name)}: ${JSON.stringify(a, null, 2).replace(/\n/g, "\n  ")}`).join(",\n");
  return `// Generated by tools/build.mjs. Do not edit.
// Sources: brand/kasseneck-logo.svg, brand/animations.json.
import type { Animation } from "./types.js";

export type LogoPart = "frame" | "corner";
export interface LogoCell { index: number; row: number; col: number; part: LogoPart }
export interface LogoGlyph { char: string; bbox: { x: number; y: number; width: number; height: number }; d: string }

/** Box of the brand file the geometry lives in. */
export const LOGO_WIDTH = ${logo.viewBox.width};
export const LOGO_HEIGHT = ${logo.viewBox.height};
/** The mark: 8×8 cells of ${logo.unit} units. */
export const GRID = ${logo.grid};
export const UNIT = ${logo.unit};

/** The open frame (two paths) and the filled corner — the brand paths, byte for byte. */
export const FRAME_PATHS = ${json(logo.signet.frame)} as const;
export const CORNER_PATH = ${json(logo.signet.corner)};

export const cells: readonly LogoCell[] = [
${cells},
];

/** Archivo 600 set as outlines: identical wherever the font is or is not. */
export const glyphs: readonly LogoGlyph[] = [
${glyphs},
];

export const animations: Readonly<Record<string, Animation>> = {
${anims},
};

export const animationNames = ${json(animations.map((a) => a.name))} as const;
export type AnimationName = (typeof animationNames)[number];
`;
}
