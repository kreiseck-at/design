import { normalize } from "./svg-path.mjs";

export const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const num = (v) => String(v);

const opsDart = (ops) =>
  ops.map((op) => {
    switch (op[0]) {
      case "M": return `KdMove(${num(op[1])}, ${num(op[2])})`;
      case "L": return `KdLine(${num(op[1])}, ${num(op[2])})`;
      case "C": return `KdCubic(${op.slice(1).map(num).join(", ")})`;
      case "Z": return "KdClose()";
    }
  }).join(", ");

const flat = (elements) => normalize(elements, { rx: 2.5 }).flat();

export function emitIconsDart(model) {
  const consts = [], names = [];
  for (const id of model.order) {
    const icon = model.icons[id];
    consts.push(`  /// ${icon.de} (${id})\n  static const KdIconData ${camel(id)} = KdIconData(stroke: [${opsDart(flat(icon.stroke))}]);`);
    names.push(`    '${id}': ${camel(id)},`);
    if (icon.filled) {
      consts.push(`  /// ${icon.de}, filled (${id}-filled)\n  static const KdIconData ${camel(id)}Filled = KdIconData(fill: [${opsDart(flat(icon.fill))}]);`);
      names.push(`    '${id}-filled': ${camel(id)}Filled,`);
    }
  }
  return `// Generated by tools/build.mjs. Do not edit.
// Sources: icons/*.svg — 24-unit grid, stroke 1.75 applied by KdIcon.

import 'icon.dart';

/// Every icon of the set as path data; draw one with [KdIcon].
abstract final class KdIcons {
${consts.join("\n\n")}

  /// Lookup by source name, e.g. \`KdIcons.byName['id']\`.
  static const Map<String, KdIconData> byName = {
${names.join("\n")}
  };
}
`;
}
