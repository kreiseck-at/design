import { toOps } from "./svg-path.mjs";

const num = (v) => (Number.isInteger(v) ? `${v}` : `${v}`);
const opsDart = (ops) =>
  ops.map((op) => {
    switch (op[0]) {
      case "M": return `KdMove(${num(op[1])}, ${num(op[2])})`;
      case "L": return `KdLine(${num(op[1])}, ${num(op[2])})`;
      case "C": return `KdCubic(${op.slice(1).map(num).join(", ")})`;
      case "Z": return "KdClose()";
    }
  }).join(", ");
const pathOps = (d) => opsDart(toOps({ tag: "path", attrs: { d } }));

const easingDart = (e) => e.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const keyframeDart = (k) => {
  const props = ["opacity", "scale", "dx", "dy", "tint", "accent", "move"].filter((p) => k[p] !== undefined).map((p) => `${p}: ${num(k[p])}`);
  return `KdLogoKeyframe(${num(k.at)}${props.length ? ", " + props.join(", ") : ""})`;
};
const trackDart = (t) => `KdLogoTrack(
        kind: KdLogoTarget.${t.kind},
        indices: [${t.indices.join(", ")}], shuffle: ${t.shuffle},${t.vectors ? `
        vectors: [${t.vectors.map(([x, y]) => `Offset(${num(x)}, ${num(y)})`).join(", ")}],` : ""}
        start: ${t.start}, stagger: ${num(t.stagger)}, duration: ${t.duration},
        easing: KdEasing.${easingDart(t.easing)}, wrap: ${t.wrap},
        before: KdLogoHold.${t.before}, after: KdLogoHold.${t.after},
        keyframes: [${t.keyframes.map(keyframeDart).join(", ")}],
      )`;
const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const cueDart = (c) => `KdLogoCue(at: ${num(c.at)}${c.haptic ? `, haptic: KdHaptic.${c.haptic}` : ""}${c.sound ? `, sound: '${c.sound}'` : ""})`;
const soundDart = (s) => `KdSound(wave: KdWave.${s.wave}, gain: ${num(s.gain)}, notes: [${s.notes.map((n) => `KdNote(${num(n.hz)}, ${num(n.ms)}${n.to === undefined ? "" : `, to: ${num(n.to)}`})`).join(", ")}])`;

export function emitLogoDart(logo, animations, sounds = {}) {
  const cells = logo.cells.map((c) => `KdLogoCell(${c.index}, ${c.row}, ${c.col}, KdLogoPart.${c.part})`).join(",\n    ");
  const glyphs = logo.glyphs
    .map((g) => `KdLogoGlyph('${g.char}', bounds: Rect.fromLTWH(${num(g.bbox.x)}, ${num(g.bbox.y)}, ${num(g.bbox.width)}, ${num(g.bbox.height)}), ops: [${opsDart(g.ops)}])`)
    .join(",\n    ");
  const anims = animations.map((a) => `  /// ${a.de} (${a.scenario}, ${a.duration} ms${a.loop ? ", loops" : ""})
  static const KdLogoAnimation ${camel(a.name)} = KdLogoAnimation(
    name: '${a.name}', label: '${a.de}', scenario: '${a.scenario}', duration: ${a.duration}, loop: ${a.loop},${a.highlight ? ` highlight: '${a.highlight}',` : ""}${a.hold ? ` hold: ${num(a.hold)},` : ""}${a.cues ? `
    cues: [${a.cues.map(cueDart).join(", ")}],` : ""}
    tracks: [
      ${a.tracks.map(trackDart).join(",\n      ")},
    ],
  );`).join("\n\n");
  return `// Generated by tools/build.mjs. Do not edit.
// Sources: brand/kasseneck-logo.svg, brand/animations.json.

import 'dart:ui';

import 'icon.dart';
import 'logo_animate.dart';

/// The Kasseneck logo as geometry: the mark's three paths and its 8×8 cells,
/// the wordmark as glyph outlines (Archivo 600 set in paths), all in the
/// ${logo.viewBox.width}×${logo.viewBox.height} box of the brand file.
abstract final class KdLogoData {
  static const double width = ${logo.viewBox.width};
  static const double height = ${logo.viewBox.height};
  static const int grid = ${logo.grid};
  static const double unit = ${logo.unit};

  /// The open frame, two paths, as in the brand file.
  static const List<List<KdOp>> frame = [
    [${pathOps(logo.signet.frame[0])}],
    [${pathOps(logo.signet.frame[1])}],
  ];

  /// The filled corner.
  static const List<KdOp> corner = [${pathOps(logo.signet.corner)}];

  /// Every filled cell of the mark, row-major.
  static const List<KdLogoCell> cells = [
    ${cells},
  ];

  /// The nine glyphs of the wordmark, left to right.
  static const List<KdLogoGlyph> glyphs = [
    ${glyphs},
  ];
}

/// The named tones the cues reach for — specs, not files.
abstract final class KdSounds {
${Object.entries(sounds).map(([n, s]) => `  static const KdSound ${camel(n)} = ${soundDart(s)};`).join("\n")}

  static const Map<String, KdSound> byName = {
${Object.keys(sounds).map((n) => `    '${n}': ${camel(n)},`).join("\n")}
  };
}

/// Every logo animation, data-defined and identical to the web package.
abstract final class KdLogoAnimations {
${anims}

  static const List<KdLogoAnimation> all = [${animations.map((a) => camel(a.name)).join(", ")}];

  static const Map<String, KdLogoAnimation> byName = {
${animations.map((a) => `    '${a.name}': ${camel(a.name)},`).join("\n")}
  };
}
`;
}
